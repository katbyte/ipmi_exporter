#!/usr/bin/env bash
#
# Regenerates the source-build formula in katbyte/homebrew-tap for a released tag.
# Usage: TAG=v1.10.1-kt.1 [TAP_DRY_RUN=1] HOMEBREW_TAP_GITHUB_TOKEN=... ./.katbyte/update-homebrew-formula.sh
set -euo pipefail

TAG="${TAG:?set TAG to the release tag, e.g. v1.10.1-kt.1}"
VERSION="${TAG#v}"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

echo "==> fetching source tarball for ${TAG}..."
curl -sSfL "https://github.com/katbyte/ipmi_exporter/archive/refs/tags/${TAG}.tar.gz" -o "$tmp/src.tar.gz"

# GitHub answers some missing tarballs with a web page rather than an error, and its hash would make a formula that never installs
tar -tzf "$tmp/src.tar.gz" > /dev/null 2>&1 || { echo "==> ${TAG} has no source tarball on GitHub yet" >&2; exit 1; }
SHA256="$(sha256sum "$tmp/src.tar.gz" | cut -d' ' -f1)"

cat > "$tmp/ipmi_exporter.rb" <<FORMULA
# typed: false
# frozen_string_literal: true

# This file is generated by the ipmi_exporter release workflow - do not edit by hand.
class IpmiExporter < Formula
  desc "Server readings over IPMI for Prometheus, katbyte's build of ipmi_exporter"
  homepage "https://github.com/katbyte/ipmi_exporter"
  url "https://github.com/katbyte/ipmi_exporter/archive/refs/tags/${TAG}.tar.gz"
  # set outright rather than left for Homebrew to guess from the tarball's name
  version "${VERSION}"
  sha256 "${SHA256}"
  license "MIT"
  head "https://github.com/katbyte/ipmi_exporter.git", branch: "master"

  depends_on "go" => :build
  depends_on "freeipmi"

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X github.com/prometheus/common/version.Version=${VERSION} -X github.com/prometheus/common/version.Revision=homebrew -X github.com/prometheus/common/version.Branch=master -X github.com/prometheus/common/version.BuildUser=homebrew")
    # the exporter won't start without its config file, so the service gets upstream's example for remote BMCs to edit. Homebrew keeps an edited copy
    (etc/"ipmi_exporter").install "ipmi_remote.yml" => "ipmi.yml"
  end

  # brew services start ipmi_exporter keeps it running. FreeIPMI's tools come from the freeipmi formula's sbin, which is not on the service's PATH
  service do
    run [opt_bin/"ipmi_exporter", "--config.file=#{etc}/ipmi_exporter/ipmi.yml", "--freeipmi.path=#{Formula["freeipmi"].opt_sbin}"]
    keep_alive true
    log_path var/"log/ipmi_exporter.log"
    error_log_path var/"log/ipmi_exporter.log"
  end

  test do
    assert_match "${VERSION}", shell_output("#{bin}/ipmi_exporter --version 2>&1")
  end
end
FORMULA

if [ "${TAP_DRY_RUN:-0}" = "1" ]; then
  echo "==> dry run; generated formula:"
  cat "$tmp/ipmi_exporter.rb"
  exit 0
fi

: "${HOMEBREW_TAP_GITHUB_TOKEN:?set HOMEBREW_TAP_GITHUB_TOKEN to a token with push access to katbyte/homebrew-tap}"
echo "==> pushing formula to katbyte/homebrew-tap..."
git clone --depth 1 "https://x-access-token:${HOMEBREW_TAP_GITHUB_TOKEN}@github.com/katbyte/homebrew-tap.git" "$tmp/tap"
mkdir -p "$tmp/tap/Formula"
cp "$tmp/ipmi_exporter.rb" "$tmp/tap/Formula/ipmi_exporter.rb"
cd "$tmp/tap"
git config user.name "ipmi_exporter-release"
git config user.email "ipmi_exporter-release@katbyte.me"
git add Formula/ipmi_exporter.rb
git diff --cached --quiet && { echo "==> formula unchanged"; exit 0; }
git commit -m "ipmi_exporter ${TAG}"
git push
echo "==> done"
